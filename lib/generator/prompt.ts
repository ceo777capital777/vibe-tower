export interface ChatMessage {
  role: "user" | "assistant";
  content: string;
}

export function buildMessages(req: GenerateRequest): ChatMessage[] {
  const first: ChatMessage = {
    role: "user",
    content: `Идея сайта:\n"""\n${req.idea}\n"""`,
  };
  if (req.previous && req.instruction) {
    return [
      first,
      { role: "assistant", content: req.previous },
      {
        role: "user",
        content: `Доработай техническое задание по инструкции ниже. Верни ПОЛНЫЙ обновлённый документ в той же структуре и с теми же заголовками. Изменяй только то, что требует инструкция, остальное сохрани.\n\nИнструкция:\n"""\n${req.instruction}\n"""`,
      },
    ];
  }
  return [first];
}

export function maxTokensFor(mode: GeneratorMode): number {
  return mode === "pro" ? 9000 : 3500;
}
